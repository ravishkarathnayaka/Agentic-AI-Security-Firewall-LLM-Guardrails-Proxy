"""
Semantic Steganography & Linguistic Syntax Entropy Guard
=======================================================
Detects advanced linguistic steganography, synonym substitution modulation,
and syntactic tree perturbation attacks where covert bits are encoded in
unusual lexical distributions rather than hidden unicode symbols.
"""

import math
import re
from dataclasses import dataclass, field
from typing import Dict, List, Optional


@dataclass
class StegoEntropyResult:
    is_blocked: bool
    risk_score: float = 0.0
    violation_code: Optional[str] = None
    details: Optional[str] = None
    lexical_entropy: float = 0.0
    anomalous_synonyms: List[str] = field(default_factory=list)


class SemanticSteganographyEntropyGuard:
    """
    Computes lexical variance and detects unnatural word choice distributions
    often generated by algorithmic linguistic steganography engines (e.g. Meteor, CovertBit).
    """

    SUSPICIOUS_UNNATURAL_TOKENS = {
        "henceforth", "wherefore", "notwithstanding", "quoth", "whilst",
        "betwixt", "peradventure", "forsooth", "yclept", "heretofore"
    }

    def __init__(self, entropy_ceiling: float = 6.2, archaic_token_threshold: int = 3):
        self.entropy_ceiling = entropy_ceiling
        self.archaic_threshold = archaic_token_threshold

    def _entropy(self, text: str) -> float:
        words = re.findall(r"\b\w+\b", text.lower())
        if not words or len(words) < 15:
            return 0.0
        freqs = {}
        for w in words:
            freqs[w] = freqs.get(w, 0) + 1
        n = len(words)
        return -sum((c / n) * math.log2(c / n) for c in freqs.values())

    def inspect_text(self, text: str) -> StegoEntropyResult:
        if not text or len(text.strip()) < 30:
            return StegoEntropyResult(is_blocked=False)

        words = set(re.findall(r"\b\w+\b", text.lower()))
        archaic_matches = list(words.intersection(self.SUSPICIOUS_UNNATURAL_TOKENS))
        ent = self._entropy(text)

        # Linguistic steganography typically exhibits unusually high entropy paired with unnatural synonym packing
        if len(archaic_matches) >= self.archaic_threshold and ent > 3.0:
            return StegoEntropyResult(
                is_blocked=True,
                risk_score=min(1.0, 0.5 + 0.15 * len(archaic_matches)),
                violation_code="LINGUISTIC_STEGANOGRAPHY_DETECTED",
                details=f"Detected statistical syntactic steganography ({len(archaic_matches)} forced unnatural tokens, entropy={ent:.2f}).",
                lexical_entropy=ent,
                anomalous_synonyms=archaic_matches
            )

        return StegoEntropyResult(
            is_blocked=False,
            lexical_entropy=ent
        )
